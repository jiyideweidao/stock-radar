function buildMarkdown(b) {
  const lines = [];
  lines.push(`# ${b.title}提要`);
  lines.push("");
  lines.push(`- 分层：${b.tier}`);
  lines.push(`- 作者：${b.author}${b.year && b.year !== "-" ? `（${b.year} 年）` : ""}`);
  if (b.note) lines.push(`- 说明：${b.note}`);
  lines.push(`- 主题：${b.theme}`);
  lines.push("- 性质：方法论学习提要，非原文摘录，未下载或分发原书 PDF。");
  lines.push("");
  lines.push("## 核心观点");
  lines.push("");
  b.core.forEach((t, i) => lines.push(`${i + 1}. ${t}`));
  lines.push("");
  lines.push("## 可执行方法");
  lines.push("");
  b.methods.forEach((t) => lines.push(`- ${t}`));
  lines.push("");
  lines.push("## 常见陷阱");
  lines.push("");
  b.pitfalls.forEach((t) => lines.push(`- ${t}`));
  lines.push("");
  return lines.join("\n");
}

function main() {
  const force = process.argv.includes("--force");

  fs.mkdirSync(path.dirname(DATA_FILE), { recursive: true });
  fs.mkdirSync(DOCS_DIR, { recursive: true });
  fs.mkdirSync(SKILL_DIR, { recursive: true });

  const knowledge = buildKnowledge();
  fs.writeFileSync(DATA_FILE, JSON.stringify(knowledge, null, 2) + "\n", "utf8");

  let writtenDocs = 0;
  let writtenSkill = 0;
  let skipped = 0;

  for (const b of BOOKS) {
    const md = buildMarkdown(b);
    for (const dir of [DOCS_DIR, SKILL_DIR]) {
      const target = path.join(dir, b.file);
      const exists = fs.existsSync(target);
      // 手写提要保留；其余文件内容变了就自动重写，没变则跳过。
      const stale = exists && !PROTECTED.has(b.file) && fs.readFileSync(target, "utf8") !== md;
      if (!force && exists && !stale) { skipped++; continue; }
      fs.writeFileSync(target, md, "utf8");
      if (dir === DOCS_DIR) writtenDocs++;
      else writtenSkill++;
    }
  }

  const byTier = TIERS.map(
    (t) => `${t} ${BOOKS.filter((b) => b.tier === t).length} 本`
  ).join(" · ");

  console.log("book-to-skill 完成");
  console.log("  knowledge.json :", DATA_FILE);
  console.log("  书籍总数       :", BOOKS.length, `（${byTier}）`);
  console.log("  docs/books     :", writtenDocs, "个新提要");
  console.log("  技能 references:", writtenSkill, "个新提要", `(skill: ${SKILL_DIR})`);
  console.log("  已存在跳过     :", skipped, "（加 --force 可覆盖重写）");
  console.log("  提示：未下载或分发任何受版权保护的书籍 PDF。");
}

main();
