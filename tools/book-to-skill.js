/* 豆瓣书目页映射（由 tools/resolve-douban.js 生成）。缺失时整段跳过，不影响主流程。 */
function loadBookLinks() {
  if (!fs.existsSync(LINKS_FILE)) return {};
  try {
    return JSON.parse(fs.readFileSync(LINKS_FILE, "utf8").replace(/^\uFEFF/, "")).links || {};
  } catch (e) {
    console.warn("book-links.json 读取失败，跳过豆瓣链接：", e.message);
    return {};
  }
}

